// Generates dist/sw.js with a precache list of every built file (offline-first, cache-busted per build).
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
const dist = new URL('../dist/', import.meta.url).pathname;
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir)) {
    const p = path.join(dir, e);
    if ((await stat(p)).isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}
const files = (await walk(dist)).filter((f) => !f.endsWith('sw.js'));
const hash = createHash('sha256');
for (const f of files) hash.update(await readFile(f));
const version = hash.digest('hex').slice(0, 12);
const urls = ['./', ...files.map((f) => './' + path.relative(dist, f).split(path.sep).join('/'))];
const sw = `// Generated by scripts/build-sw.mjs
const CACHE = 'valleybook-v68-${version}';
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('./index.html').then((r) => r || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((r) => r || fetch(req).then((res) => {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
    return res;
  })));
});
`;
await writeFile(path.join(dist, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
