// Generates dist/sw.js with a precache list of every built file (offline-first, cache-busted per build).
// v7.2.2: per-file revisions (unchanged files are copied from the previous cache instead of re-downloaded), every
// download is revalidated and checked against its build hash (so a stale CDN/HTTP-cache copy of index.html can never
// be stored), the app shell must install completely while sprites/sounds are best-effort, failed responses are never
// cached, and the previous version's script chunks are kept so a page still open on it can finish loading its screens.
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
const dist = new URL('../dist/', import.meta.url).pathname;
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir)) {
    const p = path.join(dir, e);
    if ((await stat(p)).isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}
const files = (await walk(dist)).filter((f) => !f.endsWith('sw.js')).sort();
const all = createHash('sha256');
const revs = {};
let bytes = 0, coreBytes = 0;
const isCore = (u) => u === './' || u === './index.html' || u.startsWith('./assets/') || u.startsWith('./icons/') || u === './manifest.webmanifest' || u.startsWith('./sprites/ui/');
for (const f of files) {
  const buf = await readFile(f);
  all.update(buf);
  const u = './' + path.relative(dist, f).split(path.sep).join('/');
  revs[u] = createHash('sha256').update(buf).digest('hex').slice(0, 12);
  bytes += buf.length;
  if (isCore(u)) coreBytes += buf.length;
}
revs['./'] = revs['./index.html'];
const version = all.digest('hex').slice(0, 12);
const urls = Object.keys(revs);
const core = urls.filter(isCore);
const rest = urls.filter((u) => !isCore(u));
const sw = `// Generated by scripts/build-sw.mjs
const CACHE = 'valleybook-v722-${version}';   // this version's app shell (index.html, script chunks, icons)
const MEDIA = 'valleybook-media';             // sprites & sounds, shared across versions: only changed files are re-downloaded
const PREV = 'valleybook-prev';               // the previous version's script chunks, for a page still open on it
const REV_KEY = './__revs.json';
const REVS = ${JSON.stringify(revs)};
const CORE = ${JSON.stringify(core)};
const REST = ${JSON.stringify(rest)};
const PRECACHE = CORE.concat(REST);

const hex = (buf) => Array.from(new Uint8Array(buf), (b) => b.toString(16).padStart(2, '0')).join('');
async function fetchChecked(u) {
  for (const mode of ['no-cache', 'reload']) {
    const res = await fetch(u, { cache: mode });
    if (!res.ok) continue;
    const h = hex(await crypto.subtle.digest('SHA-256', await res.clone().arrayBuffer())).slice(0, 12);
    if (h === REVS[u]) return res;
  }
  throw new Error('precache: ' + u);
}
async function pool(list, n, fn) {
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < list.length) await fn(list[i++]); }));
}
async function readRevs(c) {
  try { const r = await c.match(REV_KEY); return r ? await r.json() : {}; } catch (e) { return {}; }
}
const writeRevs = (c, revs) => c.put(REV_KEY, new Response(JSON.stringify(revs), { headers: { 'content-type': 'application/json' } }));
self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // App shell: all or nothing (if anything fails, the browser retries the install later and the current version keeps working).
    const oldKeys = (await caches.keys()).filter((k) => k.startsWith('valleybook-v') && k !== CACHE);
    await pool(CORE, 6, async (u) => {
      let res;
      if (u.startsWith('./assets/')) for (const k of oldKeys) { res = await (await caches.open(k)).match(u); if (res) break; } // hashed name = same file
      await cache.put(u, res || await fetchChecked(u));
    });
    // Sprites & sounds: fetch only what's new or changed; best effort (anything missed is fetched when first shown).
    const media = await caches.open(MEDIA);
    const have = await readRevs(media);
    const todo = REST.filter((u) => have[u] !== REVS[u]);
    let n = 0;
    await pool(todo, 6, async (u) => {
      try { await media.put(u, await fetchChecked(u)); have[u] = REVS[u]; } catch (err) { delete have[u]; }
      if (++n % 100 === 0) await writeRevs(media, have);
    });
    await writeRevs(media, have);
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const cur = await caches.open(CACHE);
    const keep = [CACHE, PREV, MEDIA];
    const olds = (await caches.keys()).filter((k) => !keep.includes(k));
    const oldApp = olds.filter((k) => k.startsWith('valleybook-v'));
    if (oldApp.length) {
      // Keep the previous version's script/style chunks so a page still open on it can load its screens.
      await caches.delete(PREV);
      const prev = await caches.open(PREV);
      for (const k of oldApp) {
        const c = await caches.open(k);
        for (const req of await c.keys()) {
          if (!new URL(req.url).pathname.includes('/assets/') || (await cur.match(req))) continue;
          const r = await c.match(req);
          if (r) await prev.put(req, r);
        }
      }
    }
    await Promise.all(olds.map((k) => caches.delete(k)));
    // Drop sprites/sounds that are no longer part of the app.
    const media = await caches.open(MEDIA);
    const want = new Set(REST.map((u) => new URL(u, self.registration.scope).href));
    want.add(new URL(REV_KEY, self.registration.scope).href);
    for (const req of await media.keys()) if (!want.has(req.url)) await media.delete(req);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('./index.html', { cacheName: CACHE }).then((r) => r || caches.match('./index.html')).then((r) => r || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((r) => r || fetch(req).then((res) => {
    // Only good responses are kept (a failed download used to be cached and stick until the next version).
    if (res.ok && res.status === 200 && res.type === 'basic') {
      const copy = res.clone();
      const u = new URL(req.url).pathname;
      const into = u.includes('/sprites/') || u.includes('/sfx/') ? MEDIA : CACHE;
      e.waitUntil(caches.open(into).then((c) => c.put(req, copy)).catch(() => {}));
    }
    return res;
  })));
});
`;
await writeFile(path.join(dist, 'sw.js'), sw);
const mb = (n) => (n / 1048576).toFixed(2) + ' MB';
console.log(`sw.js: ${urls.length} files precached (${core.length} app-shell ${mb(coreBytes)} + ${rest.length} sprites/sounds), ${mb(bytes)} total, version ${version}`);
